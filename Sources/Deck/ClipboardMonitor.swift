import AppKit
import Combine

/// **What was copied**, most recent first: text, links, files and images,
/// ready to be put back on the clipboard with a click.
///
/// The pasteboard has no change notification, so its change count is polled —
/// twice a second, which costs nothing. Anything a password manager or the
/// system marks as concealed or transient is never recorded (the
/// nspasteboard.org conventions), nor is anything copied while a password
/// manager is frontmost. Text, links and files are kept across launches when
/// that is switched on; images only ever live in memory.
@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    struct Item: Identifiable, Equatable, Codable {
        enum Kind: String, Codable { case text, link, file, image }

        var id = UUID()
        var kind: Kind
        /// The text itself, the link, or the files' paths one per line.
        var text: String
        var copiedAt: Date
        var pinned = false
        /// The app it was copied from, where known.
        var sourceApp: String?
        /// PNG data for an image. Never encoded: images are not written to disk.
        var image: Data?

        enum CodingKeys: String, CodingKey { case id, kind, text, copiedAt, pinned, sourceApp }

        var fileURLs: [URL] {
            guard kind == .file else { return [] }
            return text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
        }

        /// One line for the card.
        var preview: String {
            switch kind {
            case .file:
                let names = fileURLs.map(\.lastPathComponent)
                return names.count > 1 ? "\(names[0]) +\(names.count - 1)" : (names.first ?? text)
            case .image:
                return L10n.t("Image")
            case .text, .link:
                return text.split(whereSeparator: \.isNewline).first.map {
                    String($0).trimmingCharacters(in: .whitespaces)
                } ?? text
            }
        }

        var symbol: String {
            switch kind {
            case .text: return "text.alignleft"
            case .link: return "link"
            case .file: return "doc"
            case .image: return "photo"
            }
        }

        /// Whether two clips are the same thing copied twice.
        func isSameContent(as other: Item) -> Bool {
            kind == other.kind && text == other.text && image == other.image
        }
    }

    @Published private(set) var items: [Item] = []
    /// The id of the clip just put back, for the card's "Copied" flash.
    @Published private(set) var lastCopiedID: UUID?

    /// How many unpinned clips are kept. Pinned ones never age out.
    var limit = 50 { didSet { trim(); save() } }
    /// Whether text, links and files survive a relaunch.
    var remembersHistory = true {
        didSet {
            guard remembersHistory != oldValue else { return }
            if remembersHistory { save() } else { deleteSavedHistory() }
        }
    }

    private let pasteboard: NSPasteboard
    private let storeURL: URL?
    private var timer: Timer?
    private var lastChangeCount: Int
    private var saveWork: DispatchWorkItem?

    /// Longest text kept, so a megabyte log copied by accident does not sit in
    /// memory and on disk forever.
    static let maxTextLength = 100_000
    /// Largest image kept, as PNG.
    static let maxImageBytes = 8 * 1024 * 1024

    /// The nspasteboard.org markers for content that should not be recorded.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
        "net.antelle.keeweb",
    ]

    /// Password managers: nothing copied while one of these is frontmost is kept.
    static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "in.sinew.Enpass-Desktop",
        "com.nordsec.nordpass",
        "me.proton.pass.electron",
    ]

    init(pasteboard: NSPasteboard = .general, storeURL: URL? = ClipboardMonitor.defaultStoreURL) {
        self.pasteboard = pasteboard
        self.storeURL = storeURL
        self.lastChangeCount = pasteboard.changeCount
        load()
    }

    nonisolated static var defaultStoreURL: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("NotchDeck", isDirectory: true)
            .appendingPathComponent("clipboard-history.json")
    }

    // MARK: - Watching

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already was copied before we looked.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    var isRunning: Bool { timer != nil }

    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let frontmost = NSWorkspace.shared.frontmostApplication
        guard !Self.ignoredApps.contains(frontmost?.bundleIdentifier ?? "") else { return }
        guard var item = Self.read(pasteboard) else { return }
        item.sourceApp = frontmost?.localizedName
        record(item)
    }

    /// Pure apart from the pasteboard it is handed, for the tests.
    static func read(_ pasteboard: NSPasteboard, now: Date = Date()) -> Item? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: ignoredTypes) else { return nil }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return Item(kind: .file, text: urls.map(\.path).joined(separator: "\n"), copiedAt: now)
        }
        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            let text = String(string.prefix(maxTextLength))
            if !trimmed.contains(where: \.isWhitespace),
               let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
               ["http", "https"].contains(scheme), url.host != nil {
                return Item(kind: .link, text: trimmed, copiedAt: now)
            }
            return Item(kind: .text, text: text, copiedAt: now)
        }
        if types.contains(NSPasteboard.PasteboardType.png.rawValue)
            || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
           let image = NSImage(pasteboard: pasteboard),
           let png = image.pngData, png.count <= maxImageBytes {
            return Item(kind: .image, text: "", copiedAt: now, image: png)
        }
        return nil
    }

    /// New clips go to the top; the same thing copied again moves up rather
    /// than appearing twice, and keeps its pin.
    func record(_ item: Item) {
        var item = item
        if let existing = items.firstIndex(where: { $0.isSameContent(as: item) }) {
            item.id = items[existing].id
            item.pinned = items[existing].pinned
            items.remove(at: existing)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    /// Fixed clips, never saved and never watched for: demo mode's, and the tests'.
    func showDemo(_ clips: [Item]) {
        stop()
        saveWork?.cancel()
        items = clips
    }

    // MARK: - Acting on a clip

    /// Puts the clip back on the clipboard, ready to paste.
    func copy(_ item: Item) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text, forType: .string)
        case .link:
            pasteboard.setString(item.text, forType: .string)
            if let url = URL(string: item.text) { pasteboard.setString(url.absoluteString, forType: .URL) }
        case .file:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let image = item.image { pasteboard.setData(image, forType: .png) }
        }
        // Ours: not a new clip, but the old one coming back to the top.
        lastChangeCount = pasteboard.changeCount
        var moved = item
        moved.copiedAt = Date()
        record(moved)
        lastCopiedID = item.id
        let id = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            MainActor.assumeIsolated {
                if self?.lastCopiedID == id { self?.lastCopiedID = nil }
            }
        }
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        trim()
        save()
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Everything but the pinned clips.
    func clear() {
        items.removeAll { !$0.pinned }
        save()
    }

    /// Pinned first, then the most recent: what the card and the menu list.
    var ordered: [Item] {
        items.filter(\.pinned) + items.filter { !$0.pinned }
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= max(1, limit)
        }
    }

    // MARK: - Keeping it

    private func load() {
        guard let storeURL, let data = try? Data(contentsOf: storeURL),
              let saved = try? JSONDecoder.clipboard.decode([Item].self, from: data)
        else { return }
        items = saved
    }

    private func save() {
        saveWork?.cancel()
        guard remembersHistory, let storeURL else { return }
        let kept = items.filter { $0.kind != .image }
        let work = DispatchWorkItem {
            do {
                try FileManager.default.createDirectory(at: storeURL.deletingLastPathComponent(),
                                                        withIntermediateDirectories: true)
                let data = try JSONEncoder.clipboard.encode(kept)
                try data.write(to: storeURL, options: [.atomic])
                // Readable by this user only: it can hold anything that was copied.
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storeURL.path)
            } catch {
                Log.usage.error("clipboard history not saved: \(error.localizedDescription, privacy: .public)")
            }
        }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.8, execute: work)
    }

    private func deleteSavedHistory() {
        saveWork?.cancel()
        guard let storeURL else { return }
        try? FileManager.default.removeItem(at: storeURL)
    }
}

private extension JSONEncoder {
    static var clipboard: JSONEncoder {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        return encoder
    }
}

private extension JSONDecoder {
    static var clipboard: JSONDecoder {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return decoder
    }
}

extension NSImage {
    /// The image as PNG, by way of its best bitmap.
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
